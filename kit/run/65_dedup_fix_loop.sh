#!/usr/bin/env bash
# After ./kit/run/60_dedup.sh --apply failed to build: undo the renames the errors point at,
# rebuild (incremental), repeat. On success: axiom check, score, local commit.
#   ./kit/run/65_dedup_fix_loop.sh          MAX_ROUNDS=6
source "$(dirname "$0")/env.sh"
MAX_ROUNDS="${MAX_ROUNDS:-6}"
[ -f "$KIT/dedup/APPLIED" ] || { echo "no applied P4 renames (kit/dedup/APPLIED missing)"; exit 1; }
for round in $(seq 1 "$MAX_ROUNDS"); do
  if [ "$round" -gt 1 ] || [ ! -f "$LOGS/build-latest.log" ] || [ "${REBUILD_FIRST:-0}" = 1 ]; then
    say "Round $round/$MAX_ROUNDS: build"
    if "$KIT/run/20_build.sh"; then
      "$KIT/run/30_check.sh"
      "$KIT/run/40_score.sh" | tail -8
      N=$("$PY" -c "import json;print(len(json.load(open('$KIT/dedup/report.json'))['renames']))")
      R=$(grep -cv '^\s*#' "$KIT/dedup/reverted.txt" 2>/dev/null || echo 0)
      git -C "$REPO" add -A "$WORK/src" "$KIT/dedup"
      git -C "$REPO" commit -q -m "P4: rename duplicate lemma names ($N planned, $R undone after build errors)

Generated by kit/run/60_dedup.sh + 65_dedup_fix_loop.sh; map kit/dedup/report.json,
undone renames kit/dedup/reverted.txt. Build OK, axioms OK." && echo "Committed locally. Push: git push"
      exit 0
    fi
  fi
  say "Round $round: undo renames named in the errors"
  set +e
  "$PY" "$KIT/tools/dedup_fix.py" "$LOGS/build-latest.log" "$WORK"
  RC=$?
  set -e
  [ "$RC" -eq 0 ] || { echo "Stopped: errors do not point at a rename. Send kit/logs/errors-latest.txt to Claude."; exit 1; }
done
echo "Reached MAX_ROUNDS=$MAX_ROUNDS. Send kit/logs/errors-latest.txt to Claude."; exit 1
