#!/usr/bin/env bash
# P4: rename duplicate theorem/lemma leaf names using Lean's reference index (.ilean).
#   ./kit/run/60_dedup.sh              dry run: plan + report (kit/dedup/report.json), no edits
#   ./kit/run/60_dedup.sh --apply      apply, rebuild, check axioms, score, commit locally
#   KINDS=theorem,lemma ./kit/run/60_dedup.sh [--apply]   theorems and lemmas only
# Needs a successful build first (the .ilean files are its output). After --apply the tree
# under grh-compact/src is the source of truth: 10_restructure / 25_fix_loop refuse to run.
source "$(dirname "$0")/env.sh"
KINDS="${KINDS:-theorem,lemma,def}"   # def included: the .ilean count matches the published 4.22% only with defs
mkdir -p "$KIT/dedup"
say "P4 plan (kinds: $KINDS)"
"$PY" "$KIT/tools/dedup_rename.py" "$WORK" --kinds "$KINDS" --report "$KIT/dedup/report.json"
[ "${1:-}" = "--apply" ] || { echo; echo "Dry run only. Review kit/dedup/report.json, then: ./kit/run/60_dedup.sh --apply"; exit 0; }

say "Apply renames"
"$PY" "$KIT/tools/dedup_rename.py" "$WORK" --kinds "$KINDS" --report "$KIT/dedup/report.json" --apply
date -u +%FT%TZ > "$KIT/dedup/APPLIED"
"$PY" "$KIT/tools/verify_static.py" "$WORK"

if "$KIT/run/20_build.sh"; then
  "$KIT/run/30_check.sh"
  "$KIT/run/40_score.sh" | tail -8
  N=$("$PY" -c "import json;print(len(json.load(open('$KIT/dedup/report.json'))['renames']))")
  git -C "$REPO" add -A "$WORK/src" "$KIT/dedup"
  git -C "$REPO" commit -q -m "P4: rename $N duplicate lemma names (kinds: $KINDS)

Generated by kit/run/60_dedup.sh from the .ilean reference index; map in kit/dedup/report.json.
Build OK, axioms OK." && echo "Committed locally. Push: git push"
else
  echo; echo "Build failed after renames. Send kit/logs/errors-latest.txt to Claude."
  echo "To undo: git checkout -- grh-compact/src && rm kit/dedup/APPLIED"
  exit 1
fi
